 await assert.rejects(()=>db.query("update predeposit_document_checks set status='matched' where id=$1",[id]),/permission denied/);
 await db.exec('reset role');
 const claim=(await db.query('select claim_predeposit_document_check($1) as r',[id])).rows[0].r;
 assert.equal(claim.status,'reviewing');
