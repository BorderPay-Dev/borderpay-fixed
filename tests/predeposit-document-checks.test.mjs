 assert.notEqual(next.lease_id,claim.lease_id);
 assert.equal((await db.query("update predeposit_document_checks set status='matched' where id=$1 and lease_id=$2 returning id",[id,claim.lease_id])).rows.length,0);
 await db.query("update predeposit_document_checks set status='needs_attention',result='{}' where id=$1 and lease_id=$2",[id,next.lease_id]);
 await assert.rejects(()=>db.query("update predeposit_document_checks set status='matched' where id=$1",[id]),/immutable/);
 await assert.rejects(()=>db.query("delete from predeposit_document_checks where id=$1",[id]),/retained/);
 console.log('PASS: document ownership, RLS, service-only claims, leases, immutable results and worker wakeup');
